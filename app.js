function normalize(value) { return value.toLocaleLowerCase().replace(/[’]/g, "'").replace(/[^a-z0-9'-]/g, "").trim(); }
function compact(value) { return value.toLocaleLowerCase().replace(/[^a-z0-9]/g, ""); }

function wordForms(value) {
  const word = normalize(value).replace(/'s$/, "");
  const forms = new Set([word]);
  if (word.length > 4 && word.endsWith("ies")) forms.add(`${word.slice(0, -3)}y`);
  if (word.length > 4 && word.endsWith("es")) forms.add(word.slice(0, -2));
  if (word.length > 3 && word.endsWith("s")) forms.add(word.slice(0, -1));
  if (word.length > 5 && word.endsWith("ing")) { forms.add(word.slice(0, -3)); forms.add(`${word.slice(0, -3)}e`); }
  if (word.length > 4 && word.endsWith("ed")) { forms.add(word.slice(0, -2)); forms.add(word.slice(0, -1)); }
  return forms;
}

function matchesGuess(word, guess) { const forms = wordForms(guess); return [...wordForms(word)].some(form => forms.has(form)); }
function tokenize(text) { return text.split(/([A-Za-z0-9]+(?:['’][A-Za-z]+)?|[^A-Za-z0-9]+)/g).filter(Boolean); }

function shouldReveal(token) {
  const word = normalize(token);
  if (!/[a-z0-9]/.test(word)) return true;
  return state.revealAll || alwaysVisible.has(word) || [...state.guessedWords].some(guess => matchesGuess(word, guess));
}

function renderText(text, container) {
  tokenize(text).forEach(token => {
    const word = normalize(token);
    if (!/[a-z0-9]/.test(word)) { container.append(document.createTextNode(token)); return; }
    const span = document.createElement("span");
    span.className = `word ${shouldReveal(token) ? "revealed" : "redacted"}`;
    span.dataset.word = word;
    span.textContent = token;
    container.append(span);
  });
}

function renderImage(image, extraClass = "") {
  const figure = document.createElement("figure");
  figure.className = `article-media ${extraClass} ${state.revealAll ? "unlocked" : "locked"}`.trim();
  const img = document.createElement("img");
  img.src = image.src; img.alt = state.revealAll ? image.alt : ""; img.loading = "lazy"; img.decoding = "async";
  figure.append(img);
  if (!state.revealAll) {
    const placeholder = document.createElement("div"); placeholder.className = "media-placeholder"; placeholder.textContent = "IMAGE REDACTED"; figure.append(placeholder);
  } else if (image.caption) {
    const caption = document.createElement("figcaption"); caption.textContent = image.caption; figure.append(caption);
  }
  return figure;
}

function renderBlock(block) {
  if (block.type === "heading") { const el = document.createElement(block.level === 3 ? "h3" : "h2"); renderText(block.text, el); return el; }
  if (block.type === "p") { const el = document.createElement("p"); renderText(block.text, el); return el; }
  if (block.type === "quote") { const el = document.createElement("blockquote"); renderText(block.text, el); return el; }
  if (block.type === "aside") {
    const aside = document.createElement("aside"); aside.className = "author-note";
    const label = document.createElement("strong"); renderText(`${block.label}: `, label);
    const text = document.createElement("span"); renderText(block.text, text); aside.append(label, text); return aside;
  }
  if (block.type === "image") return renderImage(block);
  if (block.type === "gallery") { const gallery = document.createElement("div"); gallery.className = "memory-gallery"; block.images.forEach(image => gallery.append(renderImage(image, "gallery-item"))); return gallery; }
  if (block.type === "note") {
    const note = document.createElement("section"); note.className = "anniversary-note";
    const heading = document.createElement("h2"); renderText(block.heading, heading); note.append(heading);
    block.paragraphs.forEach(text => { const p = document.createElement("p"); renderText(text, p); note.append(p); }); return note;
  }
  return document.createDocumentFragment();
}

function renderArticle() {
  els.title.replaceChildren(); renderText(article.title, els.title); els.body.replaceChildren();
  article.blocks.forEach(block => els.body.append(renderBlock(block)));
}

function blockText(block) {
  if (["heading", "p", "quote", "aside"].includes(block.type)) return [block.label, block.text].filter(Boolean);
  if (block.type === "note") return [block.heading, ...block.paragraphs];
  if (block.type === "image") return block.caption ? [block.caption] : [];
  return [];
}
function allWords() { return [article.title, ...article.blocks.flatMap(blockText)].flatMap(tokenize).map(normalize).filter(word => /[a-z0-9]/.test(word)); }
function titleWords() { return tokenize(article.title).map(normalize).filter(word => /[a-z0-9]/.test(word)); }
function isTitleSolved() { return titleWords().every(word => [...state.guessedWords].some(guess => matchesGuess(word, guess))); }
function countWord(guess) { return allWords().filter(word => matchesGuess(word, guess)).length; }

function updateStats() {
  const hits = state.guesses.filter(item => item.hits > 0).length;
  els.guessCount.textContent = state.guesses.length; els.hitCount.textContent = hits;
  els.accuracy.textContent = state.guesses.length ? `${Math.round((hits / state.guesses.length) * 100)}%` : "—";
}
function updateHistory() {
  els.history.replaceChildren(); els.emptyHistory.hidden = state.guesses.length > 0;
  [...state.guesses].reverse().forEach(item => {
    const li = document.createElement("li"); if (item.hits) li.classList.add("hit");
    const guess = document.createElement("span"); guess.textContent = item.word;
    const hits = document.createElement("span"); hits.textContent = item.hits; li.append(guess, hits); els.history.append(li);
  });
}
function flashWord(word) {
  document.querySelectorAll("[data-word]").forEach(node => {
    if (!matchesGuess(node.dataset.word, word)) return;
    node.classList.remove("redacted"); node.classList.add("revealed", "just-revealed");
    window.setTimeout(() => node.classList.remove("just-revealed"), 1100);
  });
}
function formatTime(ms) {
  const total = Math.floor(ms / 1000), minutes = Math.floor(total / 60), seconds = total % 60;
  return minutes ? `${minutes}m${String(seconds).padStart(2, "0")}s` : `${seconds}s`;
}
function finishGame(gaveUp = false) {
  state.solved = true; state.gaveUp = gaveUp; state.revealAll = true; clearInterval(state.timerId); renderArticle();
  els.input.disabled = true; els.form.querySelector("button[type='submit']").disabled = true; els.hintButton.disabled = true;
  const time = formatTime(Date.now() - state.startTime);
  const guessText = `${state.guesses.length} ${state.guesses.length === 1 ? "guess" : "guesses"}`;
  const hintText = state.hintsUsed ? ` and ${state.hintsUsed} ${state.hintsUsed === 1 ? "hint" : "hints"}` : "";
  els.winSummary.textContent = gaveUp ? `The whole page was unveiled after ${guessText}${hintText}.` : `You uncovered Hammond Castle in ${time} using ${guessText}${hintText}. The whole page is now unveiled.`;
  window.setTimeout(() => els.win.showModal(), 350);
}

function useHint() {
  if (state.solved || state.hintsUsed >= hints.length) return;
  const hint = hints[state.hintsUsed];
  state.hintsUsed += 1;
  const item = document.createElement("li");
  item.textContent = hint;
  els.hintList.append(item);
  els.hintPanel.hidden = false;
  els.hintProgress.textContent = `${state.hintsUsed}/${hints.length}`;
  els.hintButton.textContent = state.hintsUsed === hints.length ? "All hints used" : "Next hint";
  els.hintButton.disabled = state.hintsUsed === hints.length;
  els.feedback.textContent = `Hint ${state.hintsUsed} revealed.`;
  els.feedback.className = "feedback";

  if (state.hintsUsed === hints.length) {
    state.guessedWords.add("castle");
    flashWord("castle");
    if (isTitleSolved()) finishGame(false);
  }
}

function makeGuess(raw) {
  const displayGuess = raw.trim();
  const phraseSolved = compact(displayGuess) === compact(article.title);
  const terms = phraseSolved ? titleWords() : [normalize(displayGuess)];
  els.feedback.className = "feedback";
  if (!terms[0] || !/[a-z0-9]/.test(terms[0])) { els.feedback.textContent = "Enter a word to guess."; return; }
  if (!phraseSolved && (state.guessedWords.has(terms[0]) || alwaysVisible.has(terms[0]))) { els.feedback.textContent = `“${terms[0]}” is already visible.`; return; }
  let hits = 0;
  terms.forEach(term => { if (!state.guessedWords.has(term)) { hits += countWord(term); state.guessedWords.add(term); flashWord(term); } });
  state.guesses.push({ word: displayGuess.toLocaleLowerCase(), hits }); updateStats(); updateHistory();
  els.feedback.textContent = hits ? `${hits} ${hits === 1 ? "match" : "matches"} found.` : `No matches for “${displayGuess}”.`;
  els.feedback.classList.add(hits ? "success" : "miss");
  if (phraseSolved || isTitleSolved()) finishGame(false);
}

function resetGame() {
  clearInterval(state.timerId); state.guesses = []; state.guessedWords = new Set(); state.hintsUsed = 0; state.startTime = Date.now(); state.solved = false; state.gaveUp = false; state.revealAll = false;
  els.input.disabled = false; els.form.querySelector("button[type='submit']").disabled = false; els.hintButton.disabled = false; els.hintButton.textContent = "Get a hint"; els.hintPanel.hidden = true; els.hintList.replaceChildren(); els.hintProgress.textContent = `0/${hints.length}`; els.feedback.textContent = "";
  if (els.win.open) els.win.close(); renderArticle(); updateStats(); updateHistory(); startTimer(); els.input.focus();
}
function startTimer() { els.timer.textContent = "0s"; state.timerId = setInterval(() => { els.timer.textContent = formatTime(Date.now() - state.startTime); }, 1000); }

function registerAgentTools() {
  const context = document.modelContext; if (!context?.registerTool) return;
  void Promise.resolve(context.registerTool({
    name: "guess_word", title: "Guess a word", description: "Submit one word to the active Redactle puzzle and reveal every matching form.",
    inputSchema: { type: "object", properties: { word: { type: "string", minLength: 1, maxLength: 40 } }, required: ["word"], additionalProperties: false },
    annotations: { readOnlyHint: false, untrustedContentHint: false },
    execute(input) {
      if (state.solved) throw new Error("The puzzle is already complete.");
      const word = normalize(input?.word ?? ""); if (!word) throw new Error("Provide exactly one word.");
      const before = state.guesses.length; makeGuess(word); const result = state.guesses[state.guesses.length - 1];
      return before === state.guesses.length ? { accepted: false, message: els.feedback.textContent } : { accepted: true, word: result.word, hits: result.hits, solved: state.solved };
    }
  })).catch(() => {});
  void Promise.resolve(context.registerTool({
    name: "read_puzzle_progress", title: "Read puzzle progress", description: "Read the current number of guesses, hits, accuracy, and whether the puzzle is solved.",
    inputSchema: { type: "object", properties: {}, additionalProperties: false }, annotations: { readOnlyHint: true, untrustedContentHint: false },
    execute() { const hits = state.guesses.filter(item => item.hits > 0).length; return { guesses: state.guesses.length, hits, accuracy: state.guesses.length ? Math.round((hits / state.guesses.length) * 100) : null, solved: state.solved }; }
  })).catch(() => {});
}

